assert.match(builderPage,/query\.mode==="legacy"\s*\?\s*<BuilderWorkspace/,"legacy editor fallback must be available without migrating the tree");
assert.match(chaiEditor,/mode=legacy/,"Chai toolbar must offer a legacy fallback");
